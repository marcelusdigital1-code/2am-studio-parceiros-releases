import React, { useState, useEffect } from 'react';
import { supabase, type ControlledEmail } from '../lib/supabase';
import { encryptCred } from '../lib/crypto';
import { PlatformIcon } from './PlatformIcon';

interface Props {
  partnerId: string;
  onClose: () => void;
  onSuccess: () => void;
}

export const CreateProfileModal: React.FC<Props> = ({
  partnerId,
  onClose,
  onSuccess,
}) => {
  const [platform, setPlatform] = useState<'tiktok' | 'youtube' | 'facebook'>('tiktok');
  const [availableEmails, setAvailableEmails] = useState<ControlledEmail[]>([]);
  const [selectedEmail, setSelectedEmail] = useState<ControlledEmail | null>(null);
  const [username, setUsername] = useState('');
  const [loadingEmails, setLoadingEmails] = useState(true);
  const [submitting, setSubmitting] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Gerar senha forte aleatória para o cofre da conta
  const [autoGeneratedPassword] = useState(() => {
    const uppers = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
    const lowers = 'abcdefghijkmnopqrstuvwxyz';
    const digits = '23456789';
    const specials = '!@#$%^&*';
    const all = uppers + lowers + digits + specials;
    const len = Math.floor(Math.random() * 5) + 12;
    const pass = [
      uppers.charAt(Math.floor(Math.random() * uppers.length)),
      lowers.charAt(Math.floor(Math.random() * lowers.length)),
      digits.charAt(Math.floor(Math.random() * digits.length)),
      specials.charAt(Math.floor(Math.random() * specials.length)),
    ];
    for (let i = 4; i < len; i++) {
      pass.push(all.charAt(Math.floor(Math.random() * all.length)));
    }
    for (let i = pass.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      const temp = pass[i];
      pass[i] = pass[j];
      pass[j] = temp;
    }
    return pass.join('');
  });

  const maskEmail = (emailStr: string | undefined): string => {
    if (!emailStr) return 'e***l@dominio.com';
    const parts = emailStr.split('@');
    if (parts.length !== 2) return 'e***l@dominio.com';
    const name = parts[0];
    const domain = parts[1];
    const maskedName = name.length > 2 ? `${name[0]}***${name[name.length - 1]}` : `${name[0]}***`;
    return `${maskedName}@${domain}`;
  };

  // Carregar pool de emails disponíveis
  useEffect(() => {
    async function loadEmailPool() {
      setLoadingEmails(true);
      try {
        const { data, error } = await supabase
          .from('controlled_emails')
          .select('*')
          .eq('status', 'available')
          .order('created_at', { ascending: true });

        if (!error && data && data.length > 0) {
          setAvailableEmails(data as ControlledEmail[]);
          setSelectedEmail(data[0] as ControlledEmail);
        } else {
          setAvailableEmails([]);
        }
      } catch (err) {
        console.error('Erro ao carregar pool de emails:', err);
      } finally {
        setLoadingEmails(false);
      }
    }

    loadEmailPool();
  }, []);

  const handleGenerateUsername = () => {
    const base = username.trim() || selectedEmail?.account_name || 'conta';
    const cleanBase = base
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]/g, '')
      .slice(0, 14);

    const prefixes = ['', 'real_', 'the_', 'oficial_', 'iam_'];
    const suffixes = ['_oficial', '_pro', '_vibes', '.daily', '_fx', '_live', '_hub', '_m', '77', '88', '99'];

    const prefix = prefixes[Math.floor(Math.random() * prefixes.length)];
    const suffix = suffixes[Math.floor(Math.random() * suffixes.length)];
    const randomNum = Math.floor(10 + Math.random() * 90);

    setUsername(`@${prefix}${cleanBase || 'conta'}${suffix}${randomNum}`);
  };

  const handleSaveProfile = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMsg(null);

    if (!username.trim()) {
      setErrorMsg('Informe o nome de utilizador (@username) para o perfil.');
      return;
    }

    if (!selectedEmail) {
      setErrorMsg('Nenhum email disponível no Pool da empresa.');
      return;
    }

    setSubmitting(true);
    try {
      // Buscar maior account_code
      const { data: allAccs } = await supabase
        .from('accounts')
        .select('account_code')
        .order('created_at', { ascending: false });

      let highestNum = 0;
      allAccs?.forEach((item) => {
        const match = item.account_code?.match(/ACC-(\d+)/i);
        if (match) {
          const num = parseInt(match[1], 10);
          if (!isNaN(num) && num > highestNum) highestNum = num;
        }
      });
      const nextAccCode = `ACC-${String(highestNum + 1).padStart(3, '0')}`;

      let formattedUsername = username.trim();
      if (!formattedUsername.startsWith('@')) {
        formattedUsername = `@${formattedUsername}`;
      }

      // Gerar idade aleatória (18 a 30 anos)
      const currentYear = new Date().getFullYear();
      const randomAge = Math.floor(Math.random() * (30 - 18 + 1)) + 18;
      const birthYear = currentYear - randomAge;
      const birthMonth = Math.floor(Math.random() * 12) + 1;
      const birthDay = Math.floor(Math.random() * 25) + 1;
      const dobFormatted = `${String(birthDay).padStart(2, '0')}/${String(birthMonth).padStart(2, '0')}/${birthYear} (${randomAge} anos)`;

      // Criar conta no banco de dados com senha encriptada
      const encPass = await encryptCred(autoGeneratedPassword);
      const { error: accInsertErr } = await supabase.from('accounts').insert({
        partner_id: partnerId,
        account_code: nextAccCode,
        platform,
        username: formattedUsername,
        password_encrypted: encPass,
        controlled_email_id: selectedEmail.id,
        birth_date: dobFormatted,
        status: 'active',
      });

      if (accInsertErr) throw accInsertErr;

      // Atualizar status do email no Pool
      await supabase
        .from('controlled_emails')
        .update({
          status: 'assigned',
          assigned_to: partnerId,
          assigned_at: new Date().toISOString(),
        })
        .eq('id', selectedEmail.id);

      // Notificar Administrador em tempo real (isolado para não falhar o cadastro se notificação falhar)
      try {
        await supabase.from('notifications').insert({
          target_type: 'admin',
          target_id: partnerId || '00000000-0000-0000-0000-000000000000',
          title: '✨ Novo Perfil Criado pelo Parceiro',
          message: `Novo Perfil ${formattedUsername} (${platform.toUpperCase()}) | Código: ${nextAccCode} | Email: ${selectedEmail.email} | Senha: ${autoGeneratedPassword}`,
          type: 'account_created',
          is_read: false,
        });
      } catch (errNotif) {
        console.error('Erro na notificação ADM:', errNotif);
      }

      onSuccess();
    } catch (err: unknown) {
      const pgErr = err as { message?: string; details?: string; hint?: string; code?: string };
      let msg = pgErr?.message || (err instanceof Error ? err.message : JSON.stringify(err));
      if (msg.includes('row-level security') || msg.includes('RLS')) {
        msg = 'Permissão RLS em falta no Supabase. Copie e execute o código da Migration 024 no SQL Editor do Supabase (supabase.com) para autorizar a gravação de perfis.';
      }
      console.error('handleSaveProfile erro:', err);
      setErrorMsg(`❌ ${msg}`);
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="fixed inset-0 bg-slate-950/85 backdrop-blur-md z-50 flex items-center justify-center p-4 animate-fade-in">
      <div className="bg-slate-900 border border-slate-800 rounded-3xl max-w-lg w-full p-6 space-y-6 shadow-2xl">
        {/* Modal Header */}
        <div className="flex items-center justify-between pb-4 border-b border-slate-800">
          <div>
            <h2 className="text-lg font-bold text-white flex items-center gap-2">
              <span>✨</span> Criar Novo Perfil de Conta
            </h2>
            <p className="text-xs text-slate-400 mt-0.5">
              Defina os dados do perfil primeiro. Poderá inicializar a sessão do Chrome Real a qualquer momento.
            </p>
          </div>
          <button
            onClick={onClose}
            className="text-slate-400 hover:text-white text-xl font-bold w-8 h-8 rounded-full flex items-center justify-center hover:bg-slate-800 transition-colors"
          >
            ✕
          </button>
        </div>

        {errorMsg && (
          <div className="p-3 bg-rose-950/80 border border-rose-800/60 text-rose-300 text-xs rounded-xl">
            ❌ {errorMsg}
          </div>
        )}

        <form onSubmit={handleSaveProfile} className="space-y-6">
          {/* Seleção de Plataforma */}
          <div>
            <label className="block text-[11px] font-bold uppercase tracking-wider text-slate-400 mb-3">
              1. Selecione a Rede Social
            </label>
            <div className="grid grid-cols-3 gap-3">
              {[
                { key: 'tiktok' as const, label: 'TikTok', activeClass: 'bg-pink-950/60 border-pink-500 text-pink-300 shadow-pink-500/10' },
                { key: 'youtube' as const, label: 'YouTube', activeClass: 'bg-red-950/60 border-red-500 text-red-300 shadow-red-500/10' },
                { key: 'facebook' as const, label: 'Facebook', activeClass: 'bg-blue-950/60 border-blue-500 text-blue-300 shadow-blue-500/10' },
              ].map((p) => (
                <button
                  key={p.key}
                  type="button"
                  onClick={() => setPlatform(p.key)}
                  className={`p-4 rounded-2xl border text-center transition-all flex flex-col items-center justify-center ${
                    platform === p.key
                      ? `${p.activeClass} font-bold shadow-lg scale-[1.02]`
                      : 'bg-slate-950 border-slate-800 text-slate-400 hover:border-slate-700'
                  }`}
                >
                  <PlatformIcon platform={p.key} className="w-8 h-8 mb-2 rounded-lg" />
                  <span className="text-sm font-bold">{p.label}</span>
                </button>
              ))}
            </div>
          </div>

          {/* Seleção de Email do Pool */}
          <div>
            <label className="block text-[11px] font-bold uppercase tracking-wider text-slate-400 mb-2">
              2. Selecione o Email Atribuído (do Pool da Empresa)
            </label>
            {loadingEmails ? (
              <div className="p-3 bg-slate-950 border border-slate-800 text-slate-500 text-xs rounded-xl italic">
                Carregando emails disponíveis...
              </div>
            ) : availableEmails.length === 0 ? (
              <div className="p-3 bg-amber-950/60 border border-amber-800/60 text-amber-300 text-xs rounded-xl">
                ⚠️ Nenhum email disponível no Pool da empresa. Solicite mais ao ADM.
              </div>
            ) : (
              <select
                value={selectedEmail?.id || ''}
                onChange={(e) => {
                  const email = availableEmails.find((em) => em.id === e.target.value);
                  setSelectedEmail(email || null);
                }}
                className="w-full bg-slate-950 border border-slate-800 rounded-xl px-4 py-2.5 text-white text-sm focus:outline-none focus:border-emerald-500 font-mono"
              >
                {availableEmails.map((em) => (
                  <option key={em.id} value={em.id}>
                    {maskEmail(em.email)}
                  </option>
                ))}
              </select>
            )}
          </div>

          {/* Nome do Perfil (@username) */}
          <div>
            <label className="block text-[11px] font-bold uppercase tracking-wider text-slate-400 mb-2">
              3. Nome do Perfil (@username)
            </label>
            <div className="flex gap-2">
              <input
                type="text"
                value={username}
                onChange={(e) => setUsername(e.target.value)}
                placeholder="Ex: @minha_conta_oficial"
                className="flex-1 bg-slate-950 border border-slate-800 rounded-xl px-4 py-2.5 text-white text-sm focus:outline-none focus:border-emerald-500 font-mono"
              />
              <button
                type="button"
                onClick={handleGenerateUsername}
                className="px-3.5 py-2.5 bg-slate-800 hover:bg-slate-700 text-amber-300 font-bold rounded-xl text-xs transition-colors shrink-0 flex items-center gap-1.5"
                title="Gerar nome único"
              >
                <span>🎲</span>
                <span>Gerar</span>
              </button>
            </div>
          </div>

          {/* Rodapé e Ação */}
          <div className="pt-4 border-t border-slate-800 flex items-center justify-between gap-3">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2.5 text-xs font-semibold text-slate-400 hover:text-white"
            >
              Cancelar
            </button>

            <button
              type="submit"
              disabled={submitting || loadingEmails || availableEmails.length === 0 || !username.trim()}
              className="px-6 py-3 bg-gradient-to-r from-emerald-600 to-teal-600 hover:from-emerald-500 hover:to-teal-500 disabled:opacity-50 text-white rounded-xl text-xs font-extrabold shadow-lg shadow-emerald-600/20 transition-all flex items-center gap-2"
            >
              <span>💾</span>
              <span>{submitting ? 'Guardando...' : 'Guardar Perfil'}</span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
