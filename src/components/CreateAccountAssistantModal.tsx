import React, { useState, useEffect, useRef, useCallback } from 'react';
import { supabase, type ControlledEmail } from '../lib/supabase';
import { encryptCred } from '../lib/crypto';
import { PlatformIcon } from './PlatformIcon';

interface Props {
  partnerId: string;
  onClose: () => void;
  onSuccess: () => void;
}

export const CreateAccountAssistantModal: React.FC<Props> = ({
  partnerId,
  onClose,
  onSuccess,
}) => {
  const [step, setStep] = useState<'setup' | 'chrome'>('setup');
  const [platform, setPlatform] = useState<'tiktok' | 'youtube' | 'facebook'>('tiktok');
  const [availableEmails, setAvailableEmails] = useState<ControlledEmail[]>([]);
  const [selectedEmail, setSelectedEmail] = useState<ControlledEmail | null>(null);
  const [username, setUsername] = useState('');
  const [loadingEmails, setLoadingEmails] = useState(true);
  const [submitting, setSubmitting] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Chrome session state
  const [chromeProfileId, setChromeProfileId] = useState<string | null>(null);
  const [chromeStatus, setChromeStatus] = useState<'closed' | 'opening' | 'ready' | 'injected' | 'page-loaded'>('closed');

  // 2FA code request states
  const [requestCodeLoading, setRequestCodeLoading] = useState(false);
  const [emailCodeValue, setEmailCodeValue] = useState<string | null>(null);
  const [emailCodeMessage, setEmailCodeMessage] = useState<string | null>(null);
  const channelRef = useRef<ReturnType<typeof supabase.channel> | null>(null);
  const pollIntervalRef = useRef<ReturnType<typeof setInterval> | null>(null);

  const clearCodeListeners = useCallback(() => {
    if (pollIntervalRef.current) {
      clearInterval(pollIntervalRef.current);
      pollIntervalRef.current = null;
    }
    if (channelRef.current) {
      supabase.removeChannel(channelRef.current);
      channelRef.current = null;
    }
  }, []);

  // Refs para os valores mais recentes (evitar stale closures nos listeners IPC)
  const chromeProfileIdRef = useRef<string | null>(null);
  const selectedEmailRef = useRef<ControlledEmail | null>(null);
  const autoGeneratedPasswordRef = useRef('');

  // Generated data
  const [lastGeneratedDOB, setLastGeneratedDOB] = useState<string | null>(null);
  const lastGeneratedDOBRef = useRef<string | null>(null);

  // A senha é definida estritamente pelo Administrador (no pool de e-mails / conta)
  useEffect(() => {
    if (selectedEmail?.password) {
      autoGeneratedPasswordRef.current = selectedEmail.password;
    } else {
      autoGeneratedPasswordRef.current = 'Sec#Parceiro2026*';
    }
  }, [selectedEmail]);

  useEffect(() => {
    chromeProfileIdRef.current = chromeProfileId;
  }, [chromeProfileId]);

  useEffect(() => {
    selectedEmailRef.current = selectedEmail;
  }, [selectedEmail]);

  useEffect(() => {
    lastGeneratedDOBRef.current = lastGeneratedDOB;
  }, [lastGeneratedDOB]);

  const maskEmail = (emailStr: string | undefined): string => {
    if (!emailStr) return 'e***l@dominio.com';
    const parts = emailStr.split('@');
    if (parts.length !== 2) return 'e***l@dominio.com';
    const name = parts[0];
    const domain = parts[1];
    const maskedName = name.length > 2 ? `${name[0]}***${name[name.length - 1]}` : `${name[0]}***`;
    return `${maskedName}@${domain}`;
  };

  // Cleanup on unmount
  useEffect(() => {
    return () => {
      clearCodeListeners();
      if (chromeProfileIdRef.current && window.electronAPI) {
        window.electronAPI.closeChromeSession(chromeProfileIdRef.current);
      }
    };
  }, [clearCodeListeners]);

  // Carregar pool de emails disponíveis
  useEffect(() => {
    async function loadEmailPool() {
      setLoadingEmails(true);
      try {
        const { data, error } = await supabase
          .from('controlled_emails')
          .select('*')
          .eq('status', 'available')
          .order('created_at', { ascending: true });

        if (!error && data && data.length > 0) {
          setAvailableEmails(data as ControlledEmail[]);
          setSelectedEmail(data[0] as ControlledEmail);
        } else {
          setAvailableEmails([]);
        }
      } catch (err) {
        console.error('Erro ao carregar pool de emails:', err);
      } finally {
        setLoadingEmails(false);
      }
    }

    loadEmailPool();
  }, []);

  // Chrome IPC event listeners
  useEffect(() => {
    if (!window.electronAPI) return;

    window.electronAPI.onChromeReady((data) => {
      setChromeProfileId(data.profileId);
      chromeProfileIdRef.current = data.profileId;
      setChromeStatus('ready');
    });

    window.electronAPI.onChromePageLoaded((data) => {
      setChromeStatus('page-loaded');
      const email = selectedEmailRef.current;
      const profileId = data.profileId;
      if (email && profileId && window.electronAPI) {
        window.electronAPI.chromeInjectCredentials({
          email: email.email,
          pass: autoGeneratedPasswordRef.current,
          profileId,
          birthDate: lastGeneratedDOBRef.current || '15/06/1998',
        });
      }
    });

    window.electronAPI.onChromeInjected(() => {
      setChromeStatus('injected');
    });

    window.electronAPI.onChromeClosed((_data) => {
      setChromeStatus('closed');
      setChromeProfileId(null);
      chromeProfileIdRef.current = null;
    });
  }, []);

  // Gerar Data Nasc e Abrir Chrome REAL
  const handleOpenChrome = useCallback(() => {
    if (!selectedEmailRef.current) return;

    const currentYear = new Date().getFullYear();
    const randomAge = Math.floor(Math.random() * (30 - 18 + 1)) + 18;
    const birthYear = currentYear - randomAge;
    const birthMonth = Math.floor(Math.random() * 12) + 1;
    const birthDay = Math.floor(Math.random() * 25) + 1;
    const dobFormatted = `${String(birthDay).padStart(2, '0')}/${String(birthMonth).padStart(2, '0')}/${birthYear} (${randomAge} anos)`;
    setLastGeneratedDOB(dobFormatted);
    lastGeneratedDOBRef.current = dobFormatted;

    const urls: Record<string, string> = {
      tiktok: 'https://www.tiktok.com/signup/phone-or-email/email',
      youtube: 'https://accounts.google.com/signup',
      facebook: 'https://www.facebook.com/r.php',
    };

    const generatedProfileId = `SIGNUP-${Date.now()}`;
    setChromeProfileId(generatedProfileId);
    chromeProfileIdRef.current = generatedProfileId;

    setChromeStatus('opening');
    setErrorMsg(null);
    setStep('chrome');

    if (window.electronAPI) {
      window.electronAPI.openChromeSignup({
        url: urls[platform],
        profileId: generatedProfileId,
        email: selectedEmailRef.current.email,
        pass: autoGeneratedPasswordRef.current,
        birthDate: dobFormatted,
        partnerId: partnerId,
        platform: platform,
      });
    } else {
      setErrorMsg('Electron não disponível. Abra a aplicação pelo atalho.');
      setChromeStatus('closed');
      setStep('setup');
    }
  }, [platform, partnerId]);

  // Re-injetar credenciais (retry manual)
  const handleReInject = useCallback(() => {
    const email = selectedEmailRef.current;
    const profileId = chromeProfileIdRef.current;
    if (!email || !profileId || !window.electronAPI) return;
    window.electronAPI.chromeInjectCredentials({
      email: email.email,
      pass: autoGeneratedPasswordRef.current,
      profileId,
      birthDate: lastGeneratedDOBRef.current || '15/06/1998',
    });
  }, []);

  // Processar resposta do ADM (recebido por Realtime ou Polling REST)
  const handleCodeResponse = useCallback((status: string, codeVal: string | null) => {
    if (status === 'responded' && codeVal) {
      setEmailCodeValue(codeVal);
      setEmailCodeMessage('✨ CÓDIGO RECEBIDO! A injetar no Chrome Real...');

      const profileId = chromeProfileIdRef.current;
      if (profileId && window.electronAPI) {
        window.electronAPI.chromeInjectCode({
          code: codeVal,
          profileId,
        });
      }

      try {
        const audioCtx = new (window.AudioContext || (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext)();
        const osc = audioCtx.createOscillator();
        const gain = audioCtx.createGain();
        osc.type = 'triangle';
        osc.frequency.setValueAtTime(523.25, audioCtx.currentTime);
        osc.frequency.setValueAtTime(659.25, audioCtx.currentTime + 0.1);
        osc.frequency.setValueAtTime(783.99, audioCtx.currentTime + 0.2);
        gain.gain.setValueAtTime(0.25, audioCtx.currentTime);
        gain.gain.exponentialRampToValueAtTime(0.01, audioCtx.currentTime + 0.4);
        osc.connect(gain);
        gain.connect(audioCtx.destination);
        osc.start();
        osc.stop(audioCtx.currentTime + 0.4);
      } catch {}

      clearCodeListeners();
    } else if (status === 'denied') {
      setEmailCodeMessage('❌ ADM negou o pedido de código.');
      clearCodeListeners();
    }
  }, [clearCodeListeners]);

  // Solicitar ao ADM o código de verificação enviado pelo TikTok/Google
  const handleRequestEmailCode = useCallback(async () => {
    const email = selectedEmailRef.current;
    if (!email) return;
    setRequestCodeLoading(true);
    setEmailCodeMessage(null);
    clearCodeListeners();

    try {
      const reqCode = 'REQ-EMAIL-' + Math.floor(1000 + Math.random() * 9000);

      const { data, error } = await supabase
        .from('code_requests')
        .insert({
          request_code: reqCode,
          partner_id: partnerId,
          account_id: null,
          email: email.email,
          password_encrypted: null,
          birth_date: lastGeneratedDOBRef.current || '15/06/2000',
          request_type: 'email_verification',
          status: 'pending',
        })
        .select()
        .single();

      if (error) throw error;

      try {
        await supabase.from('notifications').insert({
          target_type: 'admin',
          target_id: partnerId || '00000000-0000-0000-0000-000000000000',
          title: '🔑 Pedido de Código 2FA Recebido',
          message: `O parceiro solicitou o código 2FA para o email ${email.email}. Código do pedido: ${reqCode}`,
          type: 'code_request',
          is_read: false,
        });
      } catch (errNotif) {
        console.error('Notificação ADM erro:', errNotif);
      }

      setEmailCodeMessage('⏳ Pedido enviado ao ADM! Aguardando o ADM enviar o código...');

      // 1. Ouvinte Realtime Supabase
      const channel = supabase
        .channel(`email_code_req_${data.id}`)
        .on(
          'postgres_changes',
          {
            event: 'UPDATE',
            schema: 'public',
            table: 'code_requests',
            filter: `id=eq.${data.id}`,
          },
          (payload: { new: Record<string, unknown> }) => {
            const updated = payload.new as unknown as {
              status: string;
              code_value: string | null;
            };
            handleCodeResponse(updated.status, updated.code_value);
          }
        )
        .subscribe();

      channelRef.current = channel;

      // 2. Fallback por Polling REST a cada 1.5 segundos
      pollIntervalRef.current = setInterval(async () => {
        try {
          const { data: pollData } = await supabase
            .from('code_requests')
            .select('status, code_value')
            .eq('id', data.id)
            .single();

          if (pollData && (pollData.status === 'responded' || pollData.status === 'denied')) {
            handleCodeResponse(pollData.status, pollData.code_value);
          }
        } catch {}
      }, 1500);

    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Erro ao solicitar código.';
      setEmailCodeMessage(`❌ ${msg}`);
    } finally {
      setRequestCodeLoading(false);
    }
  }, [partnerId, clearCodeListeners, handleCodeResponse]);

  // Guardar conta no Supabase
  const handleCreateAccount = useCallback(async () => {
    const email = selectedEmailRef.current;
    if (!email || !username.trim()) return;
    setSubmitting(true);
    setErrorMsg(null);

    try {
      const { data: allAccs } = await supabase
        .from('accounts')
        .select('account_code')
        .order('created_at', { ascending: false });

      let highestNum = 0;
      allAccs?.forEach((item) => {
        const match = item.account_code?.match(/ACC-(\d+)/i);
        if (match) {
          const num = parseInt(match[1], 10);
          if (!isNaN(num) && num > highestNum) highestNum = num;
        }
      });
      const nextAccCode = `ACC-${String(highestNum + 1).padStart(3, '0')}`;

      let formattedUsername = username.trim();
      if (!formattedUsername.startsWith('@')) {
        formattedUsername = `@${formattedUsername}`;
      }

      const dob = lastGeneratedDOBRef.current || '15/06/2000';

      const encPass = await encryptCred(autoGeneratedPasswordRef.current);
      const { error: accInsertErr } = await supabase.from('accounts').insert({
        partner_id: partnerId,
        account_code: nextAccCode,
        platform,
        username: formattedUsername,
        password_encrypted: encPass,
        controlled_email_id: email.id,
        birth_date: dob,
        status: 'active',
      });

      if (accInsertErr) throw accInsertErr;

      await supabase
        .from('controlled_emails')
        .update({
          status: 'assigned',
          assigned_to: partnerId,
          assigned_at: new Date().toISOString(),
        })
        .eq('id', email.id);

      await supabase.from('notifications').insert({
        target_type: 'admin',
        target_id: partnerId,
        title: '✨ Nova Conta Criada pelo Parceiro',
        message: `Nova Conta ${formattedUsername} (${platform.toUpperCase()}) | Email: ${email.email} | Senha: ${autoGeneratedPasswordRef.current} | Data Nasc: ${dob}`,
        type: 'account_created',
        is_read: false,
      });

      const profileId = chromeProfileIdRef.current;
      if (profileId && window.electronAPI) {
        window.electronAPI.closeChromeSession(profileId);
      }

      onSuccess();
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Erro ao cadastrar conta no sistema.';
      console.error(err);
      setErrorMsg(msg);
    } finally {
      setSubmitting(false);
    }
  }, [partnerId, platform, username, onSuccess]);

  const handleGenerateUsername = useCallback(() => {
    const base = username.trim() || selectedEmailRef.current?.account_name || 'conta';
    const cleanBase = base
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9]/g, '')
      .slice(0, 14);

    const prefixes = ['', 'real_', 'the_', 'oficial_', 'iam_'];
    const suffixes = ['_oficial', '_pro', '_vibes', '.daily', '_fx', '_live', '_hub', '_m', '77', '88', '99'];

    const prefix = prefixes[Math.floor(Math.random() * prefixes.length)];
    const suffix = suffixes[Math.floor(Math.random() * suffixes.length)];
    const randomNum = Math.floor(10 + Math.random() * 90);

    setUsername(`@${prefix}${cleanBase || 'conta'}${suffix}${randomNum}`);
  }, [username]);

  // ===============================================================
  // PASSO 2: MODO CHROME REAL (CONTROLE DE BARRA SUPERIOR)
  // ===============================================================
  if (step === 'chrome') {
    return (
      <div className="fixed inset-0 bg-slate-950 z-50 flex flex-col animate-fade-in">
        {/* Barra Superior de Controle */}
        <div className="bg-slate-900 border-b border-slate-800 px-6 py-3 flex flex-wrap items-center justify-between gap-3 shadow-xl z-20">
          <div className="flex items-center gap-3">
            <PlatformIcon platform={platform} className="w-7 h-7 shrink-0 rounded-lg" />
            <div>
              <div className="flex items-center gap-2">
                <h3 className="font-bold text-sm text-white">Chrome Real — Cadastro {platform.toUpperCase()}</h3>
                <span className="text-[10px] bg-emerald-950 text-emerald-400 border border-emerald-800/50 px-2 py-0.5 rounded-full font-mono font-bold">
                  Email: {maskEmail(selectedEmail?.email)}
                </span>
                <span className="text-[10px] bg-blue-950 text-blue-300 border border-blue-800/50 px-2 py-0.5 rounded-full font-bold">
                  🌐 Google Login 100% Suportado
                </span>
              </div>
              <p className="text-[11px] text-slate-400">
                O Chrome Real está aberto. Pode fazer login com a Conta Google ou injetar o email cegamente.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleReInject}
              className="px-4 py-2 bg-gradient-to-r from-emerald-600 to-teal-600 hover:from-emerald-500 hover:to-teal-500 text-white rounded-xl text-xs font-extrabold shadow-md shadow-emerald-600/20 transition-all flex items-center gap-2"
            >
              <span>⚡</span>
              <span>Injetar Email e Senha Cegos</span>
            </button>

            <button
              type="button"
              onClick={handleRequestEmailCode}
              disabled={requestCodeLoading}
              className="px-4 py-2 bg-gradient-to-r from-amber-600 to-orange-600 hover:from-amber-500 hover:to-orange-500 text-white rounded-xl text-xs font-extrabold shadow-md transition-all flex items-center gap-2 disabled:opacity-50"
            >
              <span>🔑</span>
              <span>{requestCodeLoading ? 'Solicitando...' : 'Pedir Código 2FA ao ADM'}</span>
            </button>

            <div className="flex items-center gap-1 bg-slate-950 p-1 rounded-xl border border-slate-800">
              <input
                type="text"
                value={username}
                onChange={(e) => setUsername(e.target.value)}
                placeholder="Ex: @username_criado"
                className="px-2 py-1 bg-transparent text-xs text-white placeholder-slate-500 font-mono focus:outline-none w-36"
              />
              <button
                type="button"
                onClick={handleGenerateUsername}
                className="px-2 py-1 bg-slate-800 hover:bg-slate-700 text-amber-300 font-bold rounded-lg text-xs transition-colors shrink-0"
                title="Gerar nome de utilizador único"
              >
                🎲
              </button>
              <button
                type="button"
                onClick={handleCreateAccount}
                disabled={submitting || !username.trim()}
                className="px-3 py-1.5 bg-blue-600 hover:bg-blue-500 disabled:opacity-50 text-white rounded-lg text-xs font-bold transition-all shrink-0"
              >
                {submitting ? 'Salvando...' : '✅ Salvar'}
              </button>
            </div>

            <button
              type="button"
              onClick={() => {
                const profileId = chromeProfileIdRef.current;
                if (profileId && window.electronAPI) {
                  window.electronAPI.closeChromeSession(profileId);
                }
                setStep('setup');
                setChromeStatus('closed');
              }}
              className="px-3 py-1.5 text-slate-400 hover:text-white text-xs font-semibold"
            >
              Fechar Chrome
            </button>
          </div>
        </div>

        {/* Status bar */}
        {(emailCodeMessage || chromeStatus === 'opening') && (
          <div
            className={`px-6 py-2 text-xs font-extrabold flex items-center justify-between border-b shadow-inner ${
              emailCodeValue
                ? 'bg-emerald-950 text-emerald-200 border-emerald-600/50'
                : 'bg-amber-950 text-amber-300 border-amber-600/50 animate-pulse'
            }`}
          >
            <span>{emailCodeMessage || '⏳ A abrir janela do Chrome Real...'}</span>
            {emailCodeValue && (
              <button
                type="button"
                onClick={() => {
                  navigator.clipboard.writeText(emailCodeValue);
                  alert('Código copiado!');
                }}
                className="px-2.5 py-1 bg-emerald-500 hover:bg-emerald-400 text-slate-950 font-bold rounded-lg text-[11px] font-mono"
              >
                📋 Copiar
              </button>
            )}
          </div>
        )}

        {/* Painel Central Informativo */}
        <div className="flex-1 bg-slate-950 flex flex-col items-center justify-center text-slate-500 text-sm">
          <div className="text-center space-y-4 p-6">
            <div className="text-6xl">🌐</div>
            <p className="font-bold text-white text-lg">Navegador Chrome Real Ativo</p>
            <p className="text-slate-300 max-w-lg text-center text-sm">
              A janela do **Google Chrome Real** abriu no seu ecrã.<br />
              Faça login com a sua **Conta Google Gmail** normalmente sem erros de bloqueio.
            </p>

            {errorMsg && (
              <div className="p-3 bg-rose-950/80 border border-rose-800/60 text-rose-300 text-xs rounded-xl max-w-md">
                ❌ {errorMsg}
              </div>
            )}

            <div className="bg-slate-900 border border-slate-800 rounded-2xl p-5 max-w-lg text-left space-y-3 shadow-xl">
              <p className="text-xs font-bold text-emerald-400 uppercase tracking-wider flex items-center gap-2">
                <span>⚡</span> Instruções de Utilização:
              </p>
              <ol className="text-xs text-slate-300 space-y-2 list-decimal list-inside leading-relaxed">
                <li>
                  <b>Login com Google:</b> Na janela do Chrome, clique em &ldquo;Continuar com o Google&rdquo; e insira o seu Gmail/senha normalmente.
                </li>
                <li>
                  <b>Injeção Automática:</b> Clique no botão <b>⚡ Injetar Email e Senha Cegos</b> acima se quiser preencher automaticamente os campos sem ver as credenciais.
                </li>
                <li>
                  <b>Código 2FA:</b> Clique em <b>🔑 Pedir Código 2FA ao ADM</b> para solicitar a verificação ao Administrador em tempo real.
                </li>
                <li>
                  <b>Finalizar:</b> Assim que a conta for criada no TikTok, insira o <b>@username</b> acima e clique em <b>✅ Salvar</b>.
                </li>
              </ol>
            </div>
          </div>
        </div>
      </div>
    );
  }

  // ===============================================================
  // PASSO 1: SELEÇÃO DE PLATAFORMA E EMAIL
  // ===============================================================
  return (
    <div className="fixed inset-0 bg-slate-950/85 backdrop-blur-md z-50 flex items-center justify-center p-4 animate-fade-in">
      <div className="bg-slate-900 border border-slate-800 rounded-3xl max-w-lg w-full p-6 space-y-6 shadow-2xl">
        {/* Modal Header */}
        <div className="flex items-center justify-between pb-4 border-b border-slate-800">
          <div>
            <h2 className="text-lg font-bold text-white flex items-center gap-2">
              <span>✨</span> Criar Nova Conta Social
            </h2>
            <p className="text-xs text-slate-400 mt-0.5">
              Chrome Real • Autenticação Google Gmail 100% Nativa
            </p>
          </div>
          <button
            onClick={onClose}
            className="text-slate-400 hover:text-white text-xl font-bold w-8 h-8 rounded-full flex items-center justify-center hover:bg-slate-800 transition-colors"
          >
            ✕
          </button>
        </div>

        {errorMsg && (
          <div className="p-3 bg-rose-950/80 border border-rose-800/60 text-rose-300 text-xs rounded-xl">
            ❌ {errorMsg}
          </div>
        )}

        <form
          onSubmit={(e) => {
            e.preventDefault();
            handleOpenChrome();
          }}
          className="space-y-6"
        >
          {/* Selecionar Plataforma */}
          <div>
            <label className="block text-[11px] font-bold uppercase tracking-wider text-slate-400 mb-3">
              Selecione a Rede Social
            </label>
            <div className="grid grid-cols-1 gap-3">
              {[
                { key: 'tiktok' as const, label: 'TikTok (Cadastro de Canal)', activeClass: 'bg-pink-950/60 border-pink-500 text-pink-300 shadow-pink-500/10' },
              ].map((p) => (
                <button
                  key={p.key}
                  type="button"
                  onClick={() => setPlatform(p.key)}
                  className={`p-4 rounded-2xl border text-center transition-all flex items-center justify-center gap-3 ${
                    platform === p.key
                      ? `${p.activeClass} font-bold shadow-lg scale-[1.01]`
                      : 'bg-slate-950 border-slate-800 text-slate-400 hover:border-slate-700'
                  }`}
                >
                  <PlatformIcon platform={p.key} className="w-8 h-8 rounded-lg shrink-0" />
                  <div className="text-left">
                    <span className="text-sm font-bold block">{p.label}</span>
                    <span className="text-[11px] text-slate-400">Preenchimento cego com e-mail e senha definidos pelo ADM</span>
                  </div>
                </button>
              ))}
            </div>
            <div className="mt-2 p-2.5 bg-blue-950/40 border border-blue-800/40 rounded-xl text-[11px] text-blue-300 flex items-start gap-2">
              <span className="text-sm shrink-0">ℹ️</span>
              <span><strong>YouTube e Facebook:</strong> As contas de YouTube e Páginas do Facebook são contas existentes fornecidas pelo Administrador e já aparecem diretamente na lista de Perfis com login automático.</span>
            </div>
          </div>

          {/* Selecionar Email do Pool */}
          {availableEmails.length > 0 && (
            <div>
              <label className="block text-[11px] font-bold uppercase tracking-wider text-slate-400 mb-3">
                Email a atribuir (do Pool da Empresa)
              </label>
              <select
                value={selectedEmail?.id || ''}
                onChange={(e) => {
                  const email = availableEmails.find((em) => em.id === e.target.value);
                  setSelectedEmail(email || null);
                }}
                className="w-full bg-slate-950 border border-slate-800 rounded-xl px-4 py-2.5 text-white text-sm focus:outline-none focus:border-emerald-500 font-mono"
              >
                {availableEmails.map((em) => (
                  <option key={em.id} value={em.id}>
                    {maskEmail(em.email)}
                  </option>
                ))}
              </select>
            </div>
          )}

          {/* Botões de Ação */}
          <div className="pt-4 border-t border-slate-800 flex items-center justify-between gap-3">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2.5 text-xs font-semibold text-slate-400 hover:text-white"
            >
              Cancelar
            </button>

            <button
              type="submit"
              disabled={loadingEmails || availableEmails.length === 0}
              className="px-6 py-3 bg-gradient-to-r from-emerald-600 to-teal-600 hover:from-emerald-500 hover:to-teal-500 disabled:opacity-50 text-white rounded-xl text-xs font-extrabold shadow-lg shadow-emerald-600/20 transition-all flex items-center gap-2"
            >
              <span>🌐</span>
              <span>
                {loadingEmails
                  ? 'Carregando Pool...'
                  : availableEmails.length === 0
                  ? 'Sem Emails no Pool'
                  : `Abrir Chrome Real — Cadastro ${platform === 'tiktok' ? 'TikTok' : platform === 'youtube' ? 'YouTube' : 'Facebook'}`}
              </span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
